#!/usr/bin/env python3
"""Regenerates vectors.h from independent reference implementations
(Python hashlib/hmac and the `cryptography` package / OpenSSL).

The kernel's crypto is checked against THESE, never against itself.
Run:  python3 tests/crypto/gen_vectors.py > tests/crypto/vectors.h
"""
import hashlib, hmac, random
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

rnd = random.Random(0x5EC7)  # fixed seed: output is reproducible

def carr(name, b):
    body = ",".join("0x%02x" % x for x in b)
    return "static const uint8_t %s[%d] = {%s};" % (name, max(len(b), 1), body if b else "0")

out = ["/* GENERATED by gen_vectors.py - do not edit by hand. */",
       "#include <stdint.h>", ""]

# SHA-256: every length 0..130 (covers all padding boundaries)
sha_msgs, n = [], 131
base = bytes(rnd.randrange(256) for _ in range(n))
out.append(carr("sha_input", base))
out.append("static const uint8_t sha_expect[%d][32] = {" % n)
for l in range(n):
    out.append("{" + ",".join("0x%02x" % x for x in hashlib.sha256(base[:l]).digest()) + "},")
out.append("};")

# HMAC: assorted key and message lengths
hm = []
for kl in (0, 1, 20, 32, 63, 64, 65, 131):
    for ml in (0, 1, 55, 64, 200):
        k = bytes(rnd.randrange(256) for _ in range(kl))
        m = bytes(rnd.randrange(256) for _ in range(ml))
        hm.append((k, m, hmac.new(k, m, hashlib.sha256).digest()))
out.append("typedef struct { const uint8_t* key; uint32_t kl; const uint8_t* msg; uint32_t ml; const uint8_t* mac; } hmac_vec_t;")
for i, (k, m, d) in enumerate(hm):
    out.append(carr("hk%d" % i, k)); out.append(carr("hm%d" % i, m)); out.append(carr("hd%d" % i, d))
out.append("static const hmac_vec_t hmac_vecs[%d] = {" % len(hm))
for i, (k, m, d) in enumerate(hm):
    out.append("{hk%d,%d,hm%d,%d,hd%d}," % (i, len(k), i, len(m), i))
out.append("};")

# PBKDF2
pb = []
for pw, salt, c, dk in [(b"password", b"salt", 1, 32), (b"password", b"salt", 2, 32),
                        (b"password", b"salt", 4096, 32), (b"passwd", b"salt", 1, 64),
                        (b"", b"", 3, 20), (b"x" * 100, b"\x00\xff" * 8, 10, 45)]:
    pb.append((pw, salt, c, dk, hashlib.pbkdf2_hmac("sha256", pw, salt, c, dk)))
out.append("typedef struct { const uint8_t* pw; uint32_t pl; const uint8_t* salt; uint32_t sl; uint32_t iter; uint32_t dk; const uint8_t* expect; } pbkdf2_vec_t;")
for i, (pw, s, c, dk, e) in enumerate(pb):
    out.append(carr("pp%d" % i, pw)); out.append(carr("ps%d" % i, s)); out.append(carr("pe%d" % i, e))
out.append("static const pbkdf2_vec_t pbkdf2_vecs[%d] = {" % len(pb))
for i, (pw, s, c, dk, e) in enumerate(pb):
    out.append("{pp%d,%d,ps%d,%d,%d,%d,pe%d}," % (i, len(pw), i, len(s), c, dk, i))
out.append("};")

# AES-256 single block: random keys/plaintexts
N = 64
keys = [bytes(rnd.randrange(256) for _ in range(32)) for _ in range(N)]
pts = [bytes(rnd.randrange(256) for _ in range(16)) for _ in range(N)]
cts = []
for k, p in zip(keys, pts):
    e = Cipher(algorithms.AES(k), modes.ECB()).encryptor()
    cts.append(e.update(p) + e.finalize())
for name, arr in (("aes_keys", keys), ("aes_pts", pts), ("aes_cts", cts)):
    w = len(arr[0])
    out.append("static const uint8_t %s[%d][%d] = {" % (name, N, w))
    for b in arr:
        out.append("{" + ",".join("0x%02x" % x for x in b) + "},")
    out.append("};")
out.append("#define AES_VEC_COUNT %d" % N)

# Internet checksum: reference per RFC 1071
def cks(d):
    s = 0
    for i in range(0, len(d) - 1, 2):
        s += (d[i] << 8) | d[i + 1]
    if len(d) & 1:
        s += d[-1] << 8
    while s >> 16:
        s = (s & 0xFFFF) + (s >> 16)
    return (~s) & 0xFFFF
ck = bytes(rnd.randrange(256) for _ in range(300))
out.append(carr("ck_input", ck))
out.append("static const uint16_t ck_expect[301] = {" + ",".join("0x%04x" % cks(ck[:l]) for l in range(301)) + "};")
print("\n".join(out))
